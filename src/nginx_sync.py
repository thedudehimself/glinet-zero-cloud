"""Atomic nginx upstreams.conf generator with nginx -t validation, rollback, and SIGHUP reload."""

from __future__ import annotations

import argparse
import ipaddress
import json
import os
import re
import signal
import subprocess
import tempfile
from pathlib import Path
from typing import Callable

SAFE_ID_RE = re.compile(r"^[a-z0-9_]+$")


def render_upstreams_conf(devices: list[dict], resolved_ips: dict[str, str]) -> str:
    blocks: list[str] = ["# Auto-generated by glinet-portal. Do not edit manually."]
    for dev in devices:
        dev_id = dev["id"]
        if not SAFE_ID_RE.match(dev_id):
            raise ValueError(f"Unsafe device id: {dev_id!r}")
        ip = resolved_ips.get(dev_id) or dev["fallback_ip"]
        ipaddress.ip_address(ip)
        port = int(dev["upstream_port"])
        blocks.append(
            f"upstream glinet_{dev_id} {{\n"
            f"    server {ip}:{port};\n"
            f"    keepalive 4;\n"
            f"}}\n"
        )
    return "\n".join(blocks)


def _atomic_write(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp_name = tempfile.mkstemp(prefix=f".{path.name}.", suffix=".tmp", dir=str(path.parent))
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as fh:
            fh.write(content)
        os.replace(tmp_name, path)
    except BaseException:
        try:
            os.unlink(tmp_name)
        except OSError:
            pass
        raise


def sync_nginx_upstreams(
    devices: list[dict],
    resolved_ips: dict[str, str],
    out_path: Path,
    nginx_conf: Path,
    pid_file: Path,
    validate_cmd: list[str] | None = None,
    reload_fn: Callable[[int], None] | None = None,
) -> dict:
    new_content = render_upstreams_conf(devices, resolved_ips)
    out_path = Path(out_path)
    old_content = out_path.read_text(encoding="utf-8") if out_path.exists() else None
    if old_content == new_content:
        return {"changed": False, "reloaded": False, "error": None}

    _atomic_write(out_path, new_content)

    cmd = validate_cmd or ["/usr/sbin/nginx", "-t", "-c", str(nginx_conf)]
    try:
        proc = subprocess.run(cmd, capture_output=True, text=True, timeout=10, check=False)
    except (OSError, subprocess.SubprocessError) as exc:
        if old_content is not None:
            _atomic_write(out_path, old_content)
        else:
            out_path.unlink(missing_ok=True)
        return {"changed": False, "reloaded": False, "error": str(exc) or type(exc).__name__}

    if proc.returncode != 0:
        if old_content is not None:
            _atomic_write(out_path, old_content)
        else:
            out_path.unlink(missing_ok=True)
        err = (proc.stderr or proc.stdout or f"validation exited {proc.returncode}").strip()
        return {"changed": False, "reloaded": False, "error": err}

    reloaded = False
    pid_file = Path(pid_file)
    if pid_file.exists():
        try:
            pid = int(pid_file.read_text(encoding="utf-8").strip())
            reloader = reload_fn or (lambda p: os.kill(p, signal.SIGHUP))
            reloader(pid)
            reloaded = True
        except (OSError, ValueError) as exc:
            return {"changed": True, "reloaded": False, "error": str(exc) or type(exc).__name__}

    return {"changed": True, "reloaded": reloaded, "error": None}


def seed_upstreams_from_config(config_path: Path, out_path: Path) -> None:
    cfg = json.loads(Path(config_path).read_text(encoding="utf-8"))
    content = render_upstreams_conf(cfg["devices"], {})
    _atomic_write(Path(out_path), content)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Seed or manage nginx upstreams.conf")
    parser.add_argument("--seed", nargs=2, metavar=("CONFIG", "OUT"), help="Seed upstreams.conf from fallback IPs")
    args = parser.parse_args()
    if args.seed:
        seed_upstreams_from_config(Path(args.seed[0]), Path(args.seed[1]))
